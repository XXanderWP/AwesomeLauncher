export type TranslationKey = keyof (typeof translations)['en']

export const languageCore = new LanguageCore(translations, 'en')

export function t(key: TranslationKey, ...args: Array<string | number>): string {
  return languageCore.translate(key, ...args)
}

export function setLanguage(lang: SupportedLanguage): void {
  languageCore.currentLanguage = lang
}

export function getCurrentLanguage(): SupportedLanguage {
  return languageCore.currentLanguage as SupportedLanguage
}
